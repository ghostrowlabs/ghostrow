import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { ColumnModel, DbKind } from "../connect/types.js";
import type { GenOutput } from "../gen/seed.js";

/**
 * File writers. Identical rows give identical bytes: LF line endings, columns in table
 * order, numbers printed without locale. One file per table for CSV and JSON; one
 * `seed.sql` script (parents first, in a transaction) for SQL, in the source's dialect.
 */

export type Format = "csv" | "sql" | "json";

function csvCell(v: unknown): string {
  if (v === null || v === undefined) return "";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (v instanceof Buffer) return v.toString("hex");
  const s = typeof v === "number" ? numberText(v) : String(v);
  return /[",\n\r]/.test(s) || /^\s|\s$/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function numberText(v: number): string {
  if (Number.isInteger(v)) return String(v);
  // Avoid 1e-7 style output and float noise like 0.30000000000000004.
  return String(Math.round(v * 1e6) / 1e6);
}

export function quoteIdent(name: string, dialect: DbKind): string {
  if (dialect === "mysql") return `\`${name.replace(/`/g, "``")}\``;
  if (dialect === "sqlserver") return `[${name.replace(/]/g, "]]")}]`;
  return `"${name.replace(/"/g, '""')}"`;
}

/** A SQL literal for a value in a column, in the target dialect. */
export function sqlLiteral(v: unknown, col: ColumnModel, dialect: DbKind): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") {
    if (dialect === "postgres") return v ? "TRUE" : "FALSE";
    return v ? "1" : "0";
  }
  if (typeof v === "number") return numberText(v);
  if (v instanceof Buffer) {
    if (dialect === "postgres") return `'\\x${v.toString("hex")}'`;
    if (dialect === "sqlserver") return `0x${v.toString("hex")}`;
    return `X'${v.toString("hex")}'`;
  }
  const s = String(v).replace(/'/g, "''");
  const prefix = dialect === "sqlserver" && /[^\x00-\x7f]/.test(s) ? "N" : "";
  if (dialect === "mysql") return `'${s.replace(/\\/g, "\\\\")}'`;
  void col;
  return `${prefix}'${s}'`;
}

export function writeCsv(out: GenOutput, dir: string): string[] {
  mkdirSync(dir, { recursive: true });
  return out.map(({ table, rows }) => {
    const lines = [table.columns.map((c) => csvCell(c.name)).join(",")];
    for (const r of rows) lines.push(table.columns.map((c) => csvCell(r[c.name])).join(","));
    const p = join(dir, `${table.name}.csv`);
    writeFileSync(p, `${lines.join("\n")}\n`, "utf8");
    return p;
  });
}

export function writeJson(out: GenOutput, dir: string): string[] {
  mkdirSync(dir, { recursive: true });
  return out.map(({ table, rows }) => {
    const stable = rows.map((r) => {
      const o: Record<string, unknown> = {};
      for (const c of table.columns) {
        const v = r[c.name];
        o[c.name] = v instanceof Buffer ? v.toString("hex") : v === undefined ? null : v;
      }
      return o;
    });
    const p = join(dir, `${table.name}.json`);
    writeFileSync(p, `${JSON.stringify(stable, null, 2)}\n`, "utf8");
    return p;
  });
}

export function sqlScript(out: GenOutput, dialect: DbKind): string {
  const parts = [`-- Generated by Ghostrow. Same schema, rules and seed give the same file.`, dialect === "sqlserver" ? "BEGIN TRANSACTION;" : "BEGIN;", ""];
  for (const { table, rows } of out) {
    if (rows.length === 0) continue;
    const cols = table.columns.filter((c) => !c.defaultValue?.startsWith("generated:"));
    const identity = dialect === "sqlserver" && cols.some((c) => c.autoIncrement);
    if (identity) parts.push(`SET IDENTITY_INSERT ${quoteIdent(table.name, dialect)} ON;`);
    const head = `INSERT INTO ${quoteIdent(table.name, dialect)} (${cols.map((c) => quoteIdent(c.name, dialect)).join(", ")})${dialect === "postgres" && cols.some((c) => /identity always/.test(c.rawType)) ? " OVERRIDING SYSTEM VALUE" : ""} VALUES`;
    // SQL Server allows at most 1000 rows per VALUES list; use 500 everywhere for readable files.
    for (let i = 0; i < rows.length; i += 500) {
      const chunk = rows.slice(i, i + 500).map((r) => `  (${cols.map((c) => sqlLiteral(r[c.name], c, dialect)).join(", ")})`);
      parts.push(`${head}\n${chunk.join(",\n")};`, "");
    }
    if (identity) parts.push(`SET IDENTITY_INSERT ${quoteIdent(table.name, dialect)} OFF;`, "");
  }
  parts.push("COMMIT;", "");
  return parts.join("\n");
}

export function writeSql(out: GenOutput, dir: string, dialect: DbKind): string {
  mkdirSync(dir, { recursive: true });
  const p = join(dir, "seed.sql");
  writeFileSync(p, sqlScript(out, dialect), "utf8");
  return p;
}

export function exportRows(out: GenOutput, dir: string, format: Format, dialect: DbKind): string[] {
  if (format === "sql") return [writeSql(out, dir, dialect)];
  if (format === "json") return writeJson(out, dir);
  return writeCsv(out, dir);
}
