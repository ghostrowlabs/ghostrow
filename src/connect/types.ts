/**
 * The schema model every source produces: a live database, a SQL DDL file, or ORM
 * models (Prisma, Django, SQLAlchemy, Laravel). The engine only ever sees this shape.
 */

export type DbKind = "postgres" | "mysql" | "sqlserver" | "sqlite";

export type ColumnType =
  | "text"
  | "integer"
  | "decimal"
  | "real"
  | "boolean"
  | "date"
  | "datetime"
  | "time"
  | "uuid"
  | "json"
  | "bytes"
  | "enum";

export interface ColumnModel {
  name: string;
  type: ColumnType;
  /** The type as declared, for messages and dialect-specific output. */
  rawType: string;
  nullable: boolean;
  primaryKey: boolean;
  /** Generated by the database (serial, identity, AUTO_INCREMENT, INTEGER PRIMARY KEY). */
  autoIncrement: boolean;
  /** Single-column UNIQUE (composite ones live on the table). */
  unique: boolean;
  defaultValue?: string;
  /** varchar(n) / char(n): maximum length. */
  maxLength?: number;
  /** numeric(p, s). */
  precision?: number;
  scale?: number;
  /** Integer width in bytes when known (smallint 2, int 4, bigint 8, tinyint 1). */
  intBytes?: number;
  enumValues?: string[];
}

export interface ForeignKey {
  columns: string[];
  refTable: string;
  refColumns: string[];
}

export interface TableModel {
  name: string;
  columns: ColumnModel[];
  primaryKey: string[];
  foreignKeys: ForeignKey[];
  /** Multi-column UNIQUE constraints (and unique indexes). */
  uniques: string[][];
  /** CHECK expressions as declared. The engine understands the common forms. */
  checks: string[];
}

export interface SchemaModel {
  dialect: DbKind;
  tables: TableModel[];
  /** Where it came from, for messages: a URL host or a file name. */
  source: string;
}

/** Sample rows per table, capped and in a stable order. Used only to confirm inferences. */
export type SampleSet = Map<string, Record<string, unknown>[]>;

export function findTable(schema: SchemaModel, name: string): TableModel | undefined {
  return schema.tables.find((t) => t.name === name) ?? schema.tables.find((t) => t.name.toLowerCase() === name.toLowerCase());
}

export function findColumn(table: TableModel, name: string): ColumnModel | undefined {
  return table.columns.find((c) => c.name === name) ?? table.columns.find((c) => c.name.toLowerCase() === name.toLowerCase());
}

/** Fill in derived fields so every source behaves the same (primary key list, PK flags). */
export function normalizeTable(t: TableModel): TableModel {
  const pk = t.primaryKey.length > 0 ? t.primaryKey : t.columns.filter((c) => c.primaryKey).map((c) => c.name);
  for (const c of t.columns) {
    if (pk.includes(c.name)) {
      c.primaryKey = true;
      c.nullable = false;
    }
  }
  const uniques = t.uniques.filter((u) => u.length > 0);
  // A single-column unique constraint is also a column flag.
  for (const u of uniques) if (u.length === 1) {
    const c = findColumn(t, u[0]!);
    if (c) c.unique = true;
  }
  return { ...t, primaryKey: pk, uniques: uniques.filter((u) => u.length > 1) };
}

export interface ParsedDbUrl {
  kind: DbKind;
  url: string;
}

/**
 * Route a connection string to its driver.
 *   postgres://, postgresql://      → postgres
 *   mysql://, mariadb://            → mysql
 *   mssql://, sqlserver://          → sqlserver
 *   sqlite:<path>, *.db, *.sqlite   → sqlite
 */
export function parseDbUrl(raw: string): ParsedDbUrl {
  const url = raw.trim();
  if (/^postgres(ql)?:\/\//i.test(url)) return { kind: "postgres", url };
  if (/^(mysql|mariadb):\/\//i.test(url)) return { kind: "mysql", url: url.replace(/^mariadb:/i, "mysql:") };
  if (/^(mssql|sqlserver):\/\//i.test(url)) return { kind: "sqlserver", url };
  if (/^sqlite:/i.test(url)) {
    const body = url.replace(/^sqlite:(\/\/)?/i, "");
    return { kind: "sqlite", url: body === "" ? ":memory:" : body };
  }
  if (/\.(db|sqlite3?|db3)$/i.test(url) || url === ":memory:") return { kind: "sqlite", url };
  throw new Error(`Unrecognised database URL "${redact(raw)}". Use postgres://, mysql://, mssql:// or sqlite:<file>.`);
}

/** A connection string with the password removed, safe to print. */
export function redact(url: string): string {
  return url.replace(/(\/\/[^:/@]+:)[^@]*@/, "$1****@");
}
